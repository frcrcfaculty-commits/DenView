// Regenerates src/utils/vendorLibs.ts from scripts/vendor/*.js so the WebView viewer
// runs fully offline (no CDN). Run: node scripts/vendor-libs.js
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, 'vendor');
const libs = {
  DICOM_PARSER_JS: 'dicomParser.min.js', // dicom-parser@1.8.21 (MIT)
  JSZIP_JS: 'jszip.min.js', // jszip@3.10.1 (MIT / GPLv3 dual)
  LOSSLESS_JS: 'lossless.js', // jpeg-lossless-decoder-js (MIT)
};

let out = '// AUTO-GENERATED by scripts/vendor-libs.js. Do not edit by hand.\n';
for (const [name, file] of Object.entries(libs)) {
  const src = fs.readFileSync(path.join(dir, file), 'utf8');
  if (/<\/script/i.test(src)) throw new Error(`${file} contains </script>`);
  out += `export const ${name}: string = ${JSON.stringify(src)};\n`;
}
const target = path.join(__dirname, '..', 'src', 'utils', 'vendorLibs.ts');
fs.writeFileSync(target, out);
console.log(`wrote ${target} (${out.length} bytes)`);
